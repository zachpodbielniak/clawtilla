# Writes one C string per file and a table of { path, content } pairs, the
# path relative to ROOT. Used for the bundled skills, so the daemon can
# install them into skills.dir without knowing where data was installed --
# the same reason data/default-config.yaml is embedded in the CLI.
#
# Usage: clawt-embed-files.sh OUTPUT ROOT FILE...

set -euo pipefail

embed_files () {
	if [[ $# -lt 2 ]]
	then
		echo 'embed_files() requires an output, a root and files'
		echo 'clawt-embed-files.sh <output> <root> <file>...'
		exit 1
	fi

	local output="${1}"
	local root="${2}"
	shift 2

	local index=0
	local file
	local tmp="${output}.tmp"

	{
		printf '/* Generated by tools/clawt-embed-files.sh. Do not edit. */\n'
		for file in "$@"
		do
			printf 'static const gchar embedded_file_%d[] =\n' "${index}"
			# Backslashes first, then quotes; each line becomes one literal.
			awk '{ gsub(/\\/, "\\\\"); gsub(/"/, "\\\""); printf "    \"%s\\n\"\n", $0 }' "${file}"
			printf '    ;\n'
			index=$((index + 1))
		done

		printf 'static const struct { const gchar *path; const gchar *content; } embedded_files[] = {\n'
		index=0
		for file in "$@"
		do
			printf '    { "%s", embedded_file_%d },\n' "${file#"${root}"/}" "${index}"
			index=$((index + 1))
		done
		printf '};\n'
	} > "${tmp}"

	mv -f "${tmp}" "${output}"
}

embed_files "$@"
